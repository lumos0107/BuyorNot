import { render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import App from './App'
import { BENEFITS_KEY } from './logic/benefits'

beforeEach(() => { localStorage.clear(); vi.useFakeTimers({ toFake: ['Date'] }); vi.setSystemTime(new Date(2026, 10, 2, 9)) })
afterEach(() => vi.useRealTimers())

it('AC151·AC152: 공식 링크에서 조건을 확인하고 직접 적은 날·상태를 저장한다', async () => {
  const user = userEvent.setup()
  render(<App />)
  await user.click(screen.getByRole('tab', { name: '모으기' }))
  await user.click(screen.getByText('받을 수 있는 돈'))
  await user.click(screen.getByText('에너지바우처'))
  const program = screen.getByRole('link', { name: '에너지바우처 공식 안내' })
  expect(program).toHaveAttribute('href', 'https://www.energyv.or.kr/info/support_info.do')
  expect(program).toHaveAttribute('target', '_blank')
  const form = within(screen.getByRole('form', { name: '에너지바우처 확인' }))
  await user.selectOptions(form.getByLabelText('상태'), 'applied')
  await user.click(form.getByRole('button', { name: '저장' }))
  expect(JSON.parse(localStorage.getItem(BENEFITS_KEY) ?? '{}').programs).toEqual([{ id: 'energy', checkedOn: '2026-11-02', status: 'applied' }])
  expect(screen.getByText('신청함 · 2026-11-02에 확인')).toBeInTheDocument()
})

it('AC153: 직접 적은 지원금은 생긴 돈에만 들어간다', async () => {
  const user = userEvent.setup()
  render(<App />)
  await user.click(screen.getByRole('tab', { name: '모으기' }))
  await user.click(screen.getByText('받을 수 있는 돈'))
  await user.click(screen.getByText('에너지바우처'))
  const form = within(screen.getByRole('form', { name: '에너지바우처 확인' }))
  await user.selectOptions(form.getByLabelText('상태'), 'receiving')
  await user.type(form.getByLabelText('받은 금액 (선택)'), '100000')
  await user.click(form.getByRole('button', { name: '저장' }))
  expect(within(screen.getByRole('region', { name: '생긴 돈' })).getByText('100,000원')).toBeInTheDocument()
  expect(screen.queryByRole('region', { name: '모으기 요약' })).not.toBeInTheDocument()
})

it('AC154·AC155: 카드 실적은 차이를 보이고 지난달 기록을 이번 달과 구분한다', async () => {
  const user = userEvent.setup()
  render(<App />)
  await user.click(screen.getByRole('tab', { name: '모으기' }))
  await user.click(screen.getByText('받을 수 있는 돈'))
  await user.click(screen.getByText('카드 실적'))
  const form = within(screen.getByRole('form', { name: '카드 실적 적기' }))
  await user.type(form.getByLabelText('카드 이름'), '생활 카드')
  await user.type(form.getByLabelText('실적 기준'), '300000')
  await user.type(form.getByLabelText('해당 월 쓴 금액'), '280000')
  await user.click(form.getByRole('button', { name: '적기' }))
  expect(screen.getByText('실적까지 20,000원')).toBeInTheDocument()
  expect(screen.queryByText(/더 쓰/)).not.toBeInTheDocument()
  expect(JSON.parse(localStorage.getItem(BENEFITS_KEY) ?? '{}').cards).toHaveLength(1)
  await user.click(within(screen.getByRole('article', { name: '생활 카드' })).getByRole('button', { name: '수정' }))
  await user.clear(form.getByLabelText('해당 월'))
  await user.type(form.getByLabelText('해당 월'), '2026-10')
  await user.click(form.getByRole('button', { name: '저장' }))
  expect(screen.getByText('2026-10 기록')).toBeInTheDocument()
  const card = within(screen.getByRole('article', { name: '생활 카드' }))
  await user.click(card.getByRole('button', { name: '지우기' }))
  await user.click(card.getByRole('button', { name: '지우기 확인' }))
  expect(JSON.parse(localStorage.getItem(BENEFITS_KEY) ?? '{}').cards).toHaveLength(0)
})

it('AC156·AC157: 포인트와 쿠폰을 만료일 순으로 보고 지난 날짜도 표시한다', async () => {
  const user = userEvent.setup()
  render(<App />)
  await user.click(screen.getByRole('tab', { name: '모으기' }))
  await user.click(screen.getByText('받을 수 있는 돈'))
  await user.click(screen.getByText('포인트·쿠폰'))
  const form = within(screen.getByRole('form', { name: '포인트·쿠폰 적기' }))
  await user.type(form.getByLabelText('이름'), '포인트')
  await user.type(form.getByLabelText('금액 (선택)'), '5000')
  await user.type(form.getByLabelText('만료일'), '2026-11-15')
  await user.click(form.getByRole('button', { name: '적기' }))
  expect(screen.getByText(/포인트.*D-13/)).toBeInTheDocument()
  expect(JSON.parse(localStorage.getItem(BENEFITS_KEY) ?? '{}').expiries).toHaveLength(1)
  expect(screen.queryByRole('region', { name: '생긴 돈' })).not.toBeInTheDocument()
})
